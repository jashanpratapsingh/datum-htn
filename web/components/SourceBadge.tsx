/**
 * Provenance stamp on every reading.
 *
 * `badge` means a real ESP32-C3 is attached and this number came off its serial
 * console. `simulator` means software. The two must never be mistaken for each
 * other, so this is stamped on every row and never hidden.
 */
export function SourceBadge({ source }: { source: 'badge' | 'simulator' }) {
  const isBadge = source === 'badge';
  return (
    <span
      className={`plate inline-flex items-center gap-1.5 rounded-[2px] border px-1.5 py-0.5 ${
        isBadge
          ? 'border-phosphor/40 text-phosphor'
          : 'border-rule text-phosphor-dim'
      }`}
      title={isBadge ? 'Read from the attached ESP32-C3 badge' : 'Generated by the simulator'}
    >
      <span
        aria-hidden="true"
        className={`h-1.5 w-1.5 rounded-full ${isBadge ? 'bg-phosphor bloom' : 'bg-phosphor-dim'}`}
      />
      {source}
    </span>
  );
}
