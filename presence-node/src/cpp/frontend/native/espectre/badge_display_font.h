/*
 * ESPectre - Badge Display Font (subset)
 *
 * A subset of the public-domain 8x8 bitmap font: the letters for "MOTION",
 * "NO MOTION" and "EARNED", the digits, and the punctuation an earned-USD
 * readout needs ("$", ".", ",", "-"). Glyph bytes are copied verbatim from
 * font8x8_basic.h by Daniel Hepper (https://github.com/dhepper/font8x8),
 * itself based on Marcel Sondaar's public-domain VGA font work. Public Domain.
 *
 * Each glyph is 8 bytes; byte N is row N of the glyph, bit K of that byte
 * (from bit 0) is column K of the row. Unknown characters render as a space.
 *
 * SPDX-License-Identifier: GPL-3.0-only
 * Commercial licensing available under separate agreement; see LICENSING.md.
 */
#pragma once

#include <cstdint>

namespace presence_node {

inline const uint8_t *badge_display_glyph(char c) {
  static constexpr uint8_t kSpace[8] = {0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00};
  static constexpr uint8_t kDollar[8] = {0x0C, 0x3E, 0x03, 0x1E, 0x30, 0x1F, 0x0C, 0x00};
  static constexpr uint8_t kComma[8] = {0x00, 0x00, 0x00, 0x00, 0x00, 0x0C, 0x0C, 0x06};
  static constexpr uint8_t kMinus[8] = {0x00, 0x00, 0x00, 0x3F, 0x00, 0x00, 0x00, 0x00};
  static constexpr uint8_t kPeriod[8] = {0x00, 0x00, 0x00, 0x00, 0x00, 0x0C, 0x0C, 0x00};
  static constexpr uint8_t k0[8] = {0x3E, 0x63, 0x73, 0x7B, 0x6F, 0x67, 0x3E, 0x00};
  static constexpr uint8_t k1[8] = {0x0C, 0x0E, 0x0C, 0x0C, 0x0C, 0x0C, 0x3F, 0x00};
  static constexpr uint8_t k2[8] = {0x1E, 0x33, 0x30, 0x1C, 0x06, 0x33, 0x3F, 0x00};
  static constexpr uint8_t k3[8] = {0x1E, 0x33, 0x30, 0x1C, 0x30, 0x33, 0x1E, 0x00};
  static constexpr uint8_t k4[8] = {0x38, 0x3C, 0x36, 0x33, 0x7F, 0x30, 0x78, 0x00};
  static constexpr uint8_t k5[8] = {0x3F, 0x03, 0x1F, 0x30, 0x30, 0x33, 0x1E, 0x00};
  static constexpr uint8_t k6[8] = {0x1C, 0x06, 0x03, 0x1F, 0x33, 0x33, 0x1E, 0x00};
  static constexpr uint8_t k7[8] = {0x3F, 0x33, 0x30, 0x18, 0x0C, 0x0C, 0x0C, 0x00};
  static constexpr uint8_t k8[8] = {0x1E, 0x33, 0x33, 0x1E, 0x33, 0x33, 0x1E, 0x00};
  static constexpr uint8_t k9[8] = {0x1E, 0x33, 0x33, 0x3E, 0x30, 0x18, 0x0E, 0x00};
  static constexpr uint8_t kA[8] = {0x0C, 0x1E, 0x33, 0x33, 0x3F, 0x33, 0x33, 0x00};
  static constexpr uint8_t kD[8] = {0x1F, 0x36, 0x66, 0x66, 0x66, 0x36, 0x1F, 0x00};
  static constexpr uint8_t kE[8] = {0x7F, 0x46, 0x16, 0x1E, 0x16, 0x46, 0x7F, 0x00};
  static constexpr uint8_t kI[8] = {0x1E, 0x0C, 0x0C, 0x0C, 0x0C, 0x0C, 0x1E, 0x00};
  static constexpr uint8_t kM[8] = {0x63, 0x77, 0x7F, 0x7F, 0x6B, 0x63, 0x63, 0x00};
  static constexpr uint8_t kN[8] = {0x63, 0x67, 0x6F, 0x7B, 0x73, 0x63, 0x63, 0x00};
  static constexpr uint8_t kO[8] = {0x1C, 0x36, 0x63, 0x63, 0x63, 0x36, 0x1C, 0x00};
  static constexpr uint8_t kR[8] = {0x3F, 0x66, 0x66, 0x3E, 0x36, 0x66, 0x67, 0x00};
  static constexpr uint8_t kT[8] = {0x3F, 0x2D, 0x0C, 0x0C, 0x0C, 0x0C, 0x1E, 0x00};
  switch (c) {
    case '$': return kDollar;
    case ',': return kComma;
    case '-': return kMinus;
    case '.': return kPeriod;
    case '0': return k0;
    case '1': return k1;
    case '2': return k2;
    case '3': return k3;
    case '4': return k4;
    case '5': return k5;
    case '6': return k6;
    case '7': return k7;
    case '8': return k8;
    case '9': return k9;
    case 'A': return kA;
    case 'D': return kD;
    case 'E': return kE;
    case 'I': return kI;
    case 'M': return kM;
    case 'N': return kN;
    case 'O': return kO;
    case 'R': return kR;
    case 'T': return kT;
    default: return kSpace;
  }
}

}  // namespace presence_node
