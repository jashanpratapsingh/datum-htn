#!/usr/bin/env node
/**
 * Emit firmware-vendor/src/facilitator_key.h from the relay's keypair.
 *
 * The relay generates keys/facilitator.json on first start (relay-proxy/src/keys.ts).
 * The ESP32 must hold the matching PUBLIC key to verify receipts, so this writes
 * it as a C initializer that firmware-vendor/src/config.h includes when present.
 * Only the public half is ever read; the header is git-ignored because the key
 * is machine-specific, not because it is secret.
 *
 *   node scripts/gen-facilitator-key.mjs [--device-id vendx-esp32c3-6e94]
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const keys = JSON.parse(readFileSync(join(root, 'keys/facilitator.json'), 'utf8'));
const pub = keys.publicKey;
if (!Array.isArray(pub) || pub.length !== 32) throw new Error('keys/facilitator.json: publicKey must be 32 bytes');

const argv = process.argv.slice(2);
const i = argv.indexOf('--device-id');
const deviceId = i >= 0 ? argv[i + 1] : null;

const rows = [];
for (let r = 0; r < 32; r += 8) rows.push('    ' + pub.slice(r, r + 8).map((b) => '0x' + b.toString(16).padStart(2, '0')).join(', '));

const out = `#pragma once
// GENERATED by scripts/gen-facilitator-key.mjs from keys/facilitator.json — do not edit.
// Facilitator Ed25519 public key (hex): ${Buffer.from(pub).toString('hex')}
#define VENDX_FACILITATOR_PUBKEY_INIT \\
  { \\
${rows.join(', \\\n')} \\
  }
${deviceId ? `#define VENDX_DEVICE_ID "${deviceId}"\n` : ''}`;

const dest = join(root, 'firmware-vendor/src/facilitator_key.h');
writeFileSync(dest, out);
console.log(`wrote ${dest} (pubkey ${Buffer.from(pub).toString('hex').slice(0, 16)}…${deviceId ? `, device id ${deviceId}` : ''})`);
